import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../app/server/app.mjs';
test('source starts an isolated service, serves the UI, and masks stored credentials', async t => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'harness-source-test-'));
  const app = await createApp({ dataDir: path.join(temporary, 'data'), defaultWorkspace: path.join(temporary, 'workspace'), distDir: path.resolve(import.meta.dirname, '../app/dist'), seedExternalSkills: false });
  const server = await new Promise(resolve => { const listener = app.listen(0, '127.0.0.1', () => resolve(listener)); });
  t.after(async () => {
    await app.locals.harness.close();
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
    const resolved = path.resolve(temporary);
    assert.ok(resolved.startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(resolved).startsWith('harness-source-test-'));
    await fs.rm(resolved, { recursive: true, force: true });
  });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (route, options = {}) => fetch(base + route, { ...options, headers: { Origin: base, 'content-type': 'application/json', ...options.headers } });
  const status = await (await request('/api/status')).json();
  assert.equal(status.version, '1.5.8');
  assert.equal(status.settingsReady, false);
  const page = await request('/');
  assert.equal(page.status, 200);
  const html = await page.text();
  const assets = [...html.matchAll(/(?:src|href)="(\/[^"#]+)"/g)].map(match => match[1]);
  assert.ok(assets.includes('/composer-controls.css'));
  assert.ok(assets.includes('/settings-ui.css'));
  for (const asset of assets) assert.equal((await request(asset)).status, 200, asset);
  const settings = await (await request('/api/settings')).json();
  const profile = settings.profiles[0];
  const placeholder = 'unit-test-placeholder-value';
  const saved = await request('/api/settings', { method: 'PUT', body: JSON.stringify({ profiles: [{ ...profile, name: 'Test connection', baseUrl: 'https://example.invalid/v1', chatModel: 'test-model', apiKey: placeholder }], activeProfileId: profile.id }) });
  assert.equal(saved.status, 200);
  const publicSettings = await (await request('/api/settings')).text();
  assert.equal(publicSettings.includes(placeholder), false);
  assert.equal((await (await request('/api/status')).json()).settingsReady, true);
  const session = await request('/api/sessions', { method: 'POST', body: JSON.stringify({ title: 'Source smoke test' }) });
  assert.equal(session.status, 201);
  assert.equal((await (await request('/api/sessions')).json()).length, 1);
});
